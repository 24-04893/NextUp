"""
pdf_export.py — Server-side PDF generation for NextUp tasks using fpdf2.
"""

import re
from datetime import date
from fpdf import FPDF, XPos, YPos


def _safe_text(value) -> str:
    """Normalize text to Latin-1 compatible ASCII/characters for core PDF fonts."""
    if value is None:
        return ""
    text = str(value)
    replacements = {
        "\u2014": "-",
        "\u2013": "-",
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2022": "*",
        "\u00b7": "-",
        "\u2264": "<=",
        "\u2265": ">=",
        "\u2192": "->",
    }
    for src, dst in replacements.items():
        text = text.replace(src, dst)
    return text.encode("latin-1", "replace").decode("latin-1")


def safe_pdf_filename(name: str, fallback: str = "task") -> str:
    """Sanitize a task name into a safe .pdf download filename."""
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", (name or "").strip()).strip("_")
    return f"{cleaned or fallback}.pdf"


def _status_label(task, today: date) -> str:
    days_left = (task.deadline - today).days
    if task.completed:
        return "Completed"
    if days_left < 0:
        return f"OVERDUE by {abs(days_left)} day(s)"
    if days_left == 0:
        return "Due Today"
    if days_left == 1:
        return "1 day left"
    return f"{days_left} days left"


class _NextUpPDF(FPDF):
    def header(self):
        self.set_fill_color(249, 115, 22)
        self.rect(0, 0, 210, 18, style="F")
        self.set_xy(14, 5)
        self.set_font("Helvetica", "B", 13)
        self.set_text_color(255, 255, 255)
        self.cell(0, 8, "NextUp - Academic Task Priority Engine", new_x=XPos.RIGHT, new_y=YPos.TOP)
        self.ln(16)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(120, 130, 145)
        self.cell(0, 8, f"Generated by NextUp | Page {self.page_no()}", align="C")


def generate_task_pdf(task, today: date, breakdown=None) -> bytes:
    """Render a single task summary (with optional score breakdown) as PDF bytes."""
    pdf = _NextUpPDF()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()

    # Title block
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(30, 41, 59)
    pdf.multi_cell(0, 9, _safe_text(task.name))
    pdf.ln(2)

    status_text = _status_label(task, today)
    pdf.set_font("Helvetica", "B", 10)
    if task.completed:
        pdf.set_text_color(21, 128, 61)
    elif (task.deadline - today).days < 0:
        pdf.set_text_color(220, 38, 38)
    else:
        pdf.set_text_color(234, 88, 12)
    pdf.cell(0, 7, _safe_text(f"Status: {status_text}   |   Exported: {today.isoformat()}"), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(4)

    # Divider
    pdf.set_draw_color(226, 232, 240)
    pdf.line(14, pdf.get_y(), 196, pdf.get_y())
    pdf.ln(6)

    # Task details table
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(0, 8, "Task Details", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(2)

    deadline_val = task.deadline_str()
    if task.deadline_time:
        deadline_val += f" at {task.deadline_time}"

    rows = [
        ("Task ID", f"#{task.id}"),
        ("Subject", task.subject or "None"),
        ("Task Type", task.task_type.capitalize()),
        ("Deadline", deadline_val),
        ("Estimated Hours", f"{task.hours_str()} hour(s)"),
        ("Difficulty", f"{task.difficulty} / 5"),
        ("Priority Score", f"{round(task.priority, 1)} pts"),
    ]
    if task.completed and task.completed_at:
        rows.append(("Completed At", str(task.completed_at)[:10]))

    for idx, (label, val) in enumerate(rows):
        fill = idx % 2 == 0
        if fill:
            pdf.set_fill_color(248, 250, 252)
        else:
            pdf.set_fill_color(255, 255, 255)
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(71, 85, 105)
        pdf.cell(52, 8, _safe_text(label), border=1, fill=True)
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(130, 8, _safe_text(val), border=1, fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    if breakdown:
        pdf.ln(8)
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(30, 41, 59)
        pdf.cell(0, 8, "Priority Score Breakdown", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(2)

        bd_rows = [
            ("Urgency", f"{breakdown['urgency']:.1f} pts", "Days left weighted by urgency"),
            ("Difficulty", f"{breakdown['difficulty']:.1f} pts", f"Difficulty {task.difficulty}/5 x 5"),
            ("Estimated Size", f"{breakdown['hours']:.1f} pts", f"Hours capped at 8h x 1.5"),
            ("Task Type", f"{breakdown['type']:.1f} pts", f"Type '{task.task_type}'"),
            ("Total Priority Score", f"{breakdown['total']:.1f} pts", "Higher score = higher priority"),
        ]
        for idx, (k, v, desc) in enumerate(bd_rows):
            is_total = idx == len(bd_rows) - 1
            pdf.set_fill_color(255, 247, 237) if is_total else pdf.set_fill_color(248, 250, 252)
            pdf.set_font("Helvetica", "B" if is_total else "", 10)
            pdf.set_text_color(15, 23, 42)
            pdf.cell(52, 8, _safe_text(k), border=1, fill=True)
            pdf.cell(38, 8, _safe_text(v), border=1, fill=True)
            pdf.set_text_color(71, 85, 105)
            pdf.cell(92, 8, _safe_text(desc), border=1, fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    return bytes(pdf.output())


def generate_tasks_list_pdf(tasks, today: date) -> bytes:
    """Render all open tasks ordered by priority as a clean PDF summary."""
    pdf = _NextUpPDF()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(0, 9, "Open Tasks Report", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(0, 6, f"Date: {today.isoformat()}  |  Total Open Tasks: {len(tasks)}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(4)

    if not tasks:
        pdf.set_font("Helvetica", "I", 11)
        pdf.set_text_color(71, 85, 105)
        pdf.cell(0, 10, "No open tasks right now. You are all caught up!", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        return bytes(pdf.output())

    # Table header
    widths = [10, 62, 28, 28, 22, 16, 16]
    headers = ["#", "Task", "Subject", "Deadline", "Type", "Hrs", "Score"]
    pdf.set_fill_color(30, 41, 59)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("Helvetica", "B", 9)
    for w, h in zip(widths, headers):
        pdf.cell(w, 8, h, border=1, fill=True, align="C" if w <= 16 else "L")
    pdf.ln()

    pdf.set_font("Helvetica", "", 9)
    for idx, t in enumerate(tasks, start=1):
        fill = idx % 2 == 0
        pdf.set_fill_color(248, 250, 252) if fill else pdf.set_fill_color(255, 255, 255)
        pdf.set_text_color(15, 23, 42)
        name_txt = _safe_text(t.name)
        if len(name_txt) > 32:
            name_txt = name_txt[:29] + "..."
        subj_txt = _safe_text(t.subject or "-")
        if len(subj_txt) > 14:
            subj_txt = subj_txt[:11] + "..."
        row_vals = [
            str(idx),
            name_txt,
            subj_txt,
            t.deadline_str(),
            _safe_text(t.task_type),
            f"{t.hours_str()}h",
            f"{round(t.priority, 1)}",
        ]
        for w, val in zip(widths, row_vals):
            pdf.cell(w, 7, val, border=1, fill=True, align="C" if w <= 16 else "L")
        pdf.ln()

    return bytes(pdf.output())
